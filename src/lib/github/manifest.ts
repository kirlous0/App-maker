export interface GitHubAppManifestConversionResponse {
  id: number;
  slug: string;
  name?: string;
  client_id: string;
  client_secret: string;
  pem: string;
  webhook_secret: string | null;
  html_url?: string;
}

export function sanitizeManifestAppName(rawName: string | undefined): string {
  const cleaned = (rawName || '')
    .trim()
    .replace(/[^A-Za-z0-9 _.-]/g, '')
    .slice(0, 32)
    .trim();
  return cleaned || 'Repo2APK Builder';
}

export function buildGitHubAppManifest(appBaseUrl: string, appName?: string) {
  const base = appBaseUrl.replace(/\/+$/, '');
  return {
    name: sanitizeManifestAppName(appName),
    url: base,
    hook_attributes: {
      url: `${base}/api/webhooks/github`,
      active: true,
    },
    redirect_url: `${base}/api/github/manifest/callback`,
    callback_urls: [`${base}/api/auth/github/callback`],
    request_oauth_on_install: true,
    public: false,
    default_permissions: {
      actions: 'write',
      contents: 'write',
      metadata: 'read',
      secrets: 'write',
      workflows: 'write',
    },
    default_events: ['workflow_run', 'workflow_job'],
  };
}

export function formatVercelGitHubAppEnv(app: GitHubAppManifestConversionResponse): string {
  const normalizedPem = app.pem.replace(/\r\n/g, '\n').trim();
  const escapedPem = normalizedPem.replace(/\n/g, '\\n');

  const lines = [
    '# Generated by Repo2APK GitHub App Manifest setup',
    '# Import this file in Vercel -> Project Settings -> Environment Variables -> Import .env',
    `GITHUB_APP_ID=${app.id}`,
    `GITHUB_APP_SLUG=${app.slug}`,
    `GITHUB_CLIENT_ID=${app.client_id}`,
    `GITHUB_CLIENT_SECRET=${app.client_secret}`,
    `GITHUB_APP_PRIVATE_KEY="${escapedPem}"`,
  ];

  if (app.webhook_secret) {
    lines.push(`GITHUB_WEBHOOK_SECRET=${app.webhook_secret}`);
  }

  return `${lines.join('\n')}\n`;
}
